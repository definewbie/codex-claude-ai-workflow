#!/usr/bin/env bash

set -euo pipefail

if [[ -n "${DUAL_NODE_BIN_DIR:-}" ]]; then
  [[ -x "$DUAL_NODE_BIN_DIR/node" ]] || {
    printf '[ACPX-E1][FAIL] DUAL_NODE_BIN_DIR does not contain an executable node\n' >&2
    exit 1
  }
  export PATH="$DUAL_NODE_BIN_DIR:$PATH"
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
MANIFEST="$REPO_ROOT/tools/acpx-e1/manifest.json"
INSTALL_ROOT="$REPO_ROOT/.tools/acpx-e1"
STAGING="$REPO_ROOT/.tools/acpx-e1.staging.$$"
AUDIT="$STAGING/audit"

fail() {
  printf '[ACPX-E1][FAIL] %s\n' "$*" >&2
  exit 1
}

field() {
  node -e 'const m=require(process.argv[1]); const v=m[process.argv[2]]; if(typeof v!=="string"||!v)process.exit(2); process.stdout.write(v)' "$MANIFEST" "$1"
}

sha256_file() {
  shasum -a 256 "$1" | awk '{print $1}'
}

cleanup() {
  rm -rf "$STAGING"
}
trap cleanup EXIT

for command in git node npm pnpm shasum; do
  command -v "$command" >/dev/null 2>&1 || fail "$command is required"
done
node -e 'const [major,minor]=process.versions.node.split(".").map(Number); process.exit(major>22||(major===22&&minor>=13)?0:1)' \
  || fail 'Node >=22.13.0 is required'

UPSTREAM_REPOSITORY="$(field upstream_repository)"
UPSTREAM_TAG="$(field upstream_tag)"
UPSTREAM_TAG_OBJECT="$(field upstream_tag_object)"
UPSTREAM_COMMIT="$(field upstream_commit)"
NPM_TARBALL_SHA="$(field upstream_npm_tarball_sha256)"
PATCH_REF="$(field patch_ref)"
PATCH_SHA="$(field patch_sha256)"
PATCH="$REPO_ROOT/tools/acpx-e1/$PATCH_REF"
POLICY_SCHEMA="$(field policy_schema)"

[[ "$(sha256_file "$PATCH")" == "$PATCH_SHA" ]] || fail 'reviewed patch SHA mismatch'
mkdir -p "$STAGING" "$AUDIT"
git clone --quiet "$UPSTREAM_REPOSITORY" "$STAGING/source"
git -C "$STAGING/source" checkout --quiet "$UPSTREAM_COMMIT"
[[ "$(git -C "$STAGING/source" rev-parse "refs/tags/$UPSTREAM_TAG")" == "$UPSTREAM_TAG_OBJECT" ]] \
  || fail 'upstream tag object mismatch'
[[ "$(git -C "$STAGING/source" rev-parse "refs/tags/$UPSTREAM_TAG^{}")" == "$UPSTREAM_COMMIT" ]] \
  || fail 'upstream tag commit mismatch'

npm pack "acpx@${UPSTREAM_TAG#v}" --pack-destination "$STAGING" >"$AUDIT/npm-pack.log" 2>&1
TARBALL="$(find "$STAGING" -maxdepth 1 -name 'acpx-*.tgz' -print -quit)"
[[ -n "$TARBALL" && "$(sha256_file "$TARBALL")" == "$NPM_TARBALL_SHA" ]] \
  || fail 'npm tarball SHA mismatch'

git -C "$STAGING/source" apply --check "$PATCH"
git -C "$STAGING/source" apply "$PATCH"

(
  cd "$STAGING/source"
  pnpm install --frozen-lockfile && pnpm test
) >"$AUDIT/build-and-test.log" 2>&1 || fail "fork dependency install/tests failed"

node - "$STAGING/source/src/e1-build-info.generated.ts" "$UPSTREAM_COMMIT" "$PATCH_SHA" <<'NODE'
const fs = require("fs");
const [path, upstream, patch] = process.argv.slice(2);
fs.writeFileSync(path,
  `// Generated by Dual after reviewed patch verification.\n` +
  `export const E1_UPSTREAM_COMMIT = ${JSON.stringify(upstream)};\n` +
  `export const E1_PATCH_SHA256 = ${JSON.stringify(patch)};\n`);
NODE
(
  cd "$STAGING/source"
  pnpm run build
) >>"$AUDIT/build-and-test.log" 2>&1 || fail "fork identity build failed"

mkdir -p "$STAGING/bin"
cat >"$STAGING/bin/acpx" <<EOF
#!/usr/bin/env bash
exec node "$INSTALL_ROOT/source/dist/cli.js" "\$@"
EOF
chmod +x "$STAGING/bin/acpx"

cat >"$AUDIT/identity.json" <<EOF
{
  "upstream_commit": "$UPSTREAM_COMMIT",
  "upstream_tag_object": "$UPSTREAM_TAG_OBJECT",
  "npm_tarball_sha256": "$NPM_TARBALL_SHA",
  "patch_sha256": "$PATCH_SHA",
  "policy_schema": "$POLICY_SCHEMA"
}
EOF

rm -rf "$INSTALL_ROOT"
mv "$STAGING" "$INSTALL_ROOT"
trap - EXIT
"$INSTALL_ROOT/bin/acpx" build-info --json | tee "$INSTALL_ROOT/audit/build-info.json"
printf '[ACPX-E1] installed %s\n' "$INSTALL_ROOT/bin/acpx"
